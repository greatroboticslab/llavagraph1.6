"""
eval_mamba2.py
==============
Evaluates the fine-tuned mamba2-780m-hf checkpoint on the 487-sample test
set: speed (ms/sample, ms/token) and text quality (BLEU-1, ROUGE-L against
the short reference labels), using the same measurement methodology as
mamba_zamba/eval_zamba.py so the two are directly comparable.

Unlike Zamba2's few-shot eval, this model was fine-tuned directly on the
task, so inference here is zero-shot: system + input -> generate. No
in-context example is built into the prompt.

Usage (on the cluster, after fine-tuning has produced checkpoints/final/):
    python eval_mamba2.py
"""

import json
import time
from pathlib import Path
from collections import defaultdict

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

MODEL_PATH     = "/projects/ya4v/llavagraph1.6/mamba2_fast/checkpoints/final"
TEST_PATH      = "/projects/ya4v/llavagraph1.6/mamba2_fast/data/test.jsonl"
RESULTS_DIR    = Path("/projects/ya4v/llavagraph1.6/mamba2_fast/results")
MAX_NEW_TOKENS = 80    # short-format target is ~40 words; generous headroom
RESULTS_DIR.mkdir(exist_ok=True)

print(f"Loading tokenizer: {MODEL_PATH}")
tokenizer = AutoTokenizer.from_pretrained(MODEL_PATH)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

print(f"Loading model: {MODEL_PATH}")
model = AutoModelForCausalLM.from_pretrained(MODEL_PATH, torch_dtype=torch.bfloat16)
model.to("cuda" if torch.cuda.is_available() else "cpu")
model.eval()

try:
    import mamba_ssm, causal_conv1d  # noqa: F401
    print("Fast SSM kernels: available")
except ImportError:
    print("WARNING: mamba_ssm/causal_conv1d not installed — speed numbers "
          "below will NOT reflect Mamba's real potential (naive PyTorch scan).")

test_data = [json.loads(l) for l in open(TEST_PATH) if l.strip()]
print(f"Test samples: {len(test_data)}")


# ── correction vector (identical formulas to eval_zamba.py — pure math, ─────
# ── never generated by the model) ────────────────────────────────────────────
import re, math

def get_wtype(ex):
    m = re.search(r"COMMANDED WAVEFORM: (\w+)", ex.get("input", ""))
    return m.group(1) if m else ex.get("waveform", "sine")

def parse_features(input_text):
    f = {}
    m = re.search(r"COMMANDED WAVEFORM: (\w+) at ([\d.]+) Hz", input_text)
    if m:
        f["waveform_type"] = m.group(1)
        f["freq"] = float(m.group(2))
    m = re.search(r"target peak \+/-([\d.]+) nm", input_text) or \
        re.search(r"target peak ±([\d.]+) nm", input_text)
    if m:
        f["target_peak"] = float(m.group(1))
    patterns = {
        "rms":          r"RMS displacement \(nm\):\s*([\d.]+)",
        "peak_disp":    r"Peak displacement \(nm\):\s*([\d.]+)",
        "h2_ratio":     r"2nd harmonic ratio:\s*([\d.]+)",
        "h3_ratio":     r"3rd harmonic ratio:\s*([\d.]+)",
        "phase_lag":    r"Phase lag \(deg\):\s*([-\d.]+)",
        "fopdt_lag":    r"FOPDT predicted phase lag \(deg\):\s*([-\d.]+)",
        "hysteresis":   r"Hysteresis \(nm\):\s*([\d.]+)",
        "duty_cycle":   r"Duty cycle:\s*([\d.]+)",
        "edge_sharpness": r"Edge sharpness:\s*([\d.]+)",
        "spectral_flat":  r"Spectral flatness:\s*([\d.]+)",
        "rise_linearity": r"Rise linearity:\s*([\d.]+)",
        "fall_linearity": r"Fall linearity:\s*([\d.]+)",
        "rise_fall_asym": r"Rise/fall asymmetry:\s*([\d.]+)",
        "post_ringing":   r"Post-pulse ringing ratio:\s*([\d.]+)",
        "pulse_duty":     r"Pulse duty cycle:\s*([\d.]+)",
        "gaussianity_err": r"Gaussianity error:\s*([\d.]+)",
        "autocorr":       r"Autocorrelation lag-1:\s*([\d.]+)",
    }
    for key, pat in patterns.items():
        m = re.search(pat, input_text)
        if m:
            f[key] = float(m.group(1))
    return f

def compute_cv(f):
    wtype = f.get("waveform_type", "sine")
    rms   = f.get("rms", 1.0) or 1.0
    peak  = f.get("target_peak", 0.0)
    h2, h3 = f.get("h2_ratio", 0.0), f.get("h3_ratio", 0.0)

    if wtype == "sine":
        phase = f.get("phase_lag", f.get("fopdt_lag", 0.0))
        amp = round(peak / (math.sqrt(2) * rms), 4) if rms > 0 else 1.0
        return {"phase_offset_deg": round(-phase, 3), "amplitude_scale": amp,
                "harmonic_2_amp": round(-h2, 4), "harmonic_3_amp": round(-h3, 4)}
    if wtype == "square":
        return {"duty_cycle_trim": round(0.5 - f.get("duty_cycle", 0.5), 4),
                "edge_sharpness_deficit": round(1.0 - f.get("edge_sharpness", 1.0), 5),
                "harmonic_2_amp": round(-h2, 5)}
    if wtype == "ramp":
        amp = round(peak / (math.sqrt(3) * rms), 4) if rms > 0 else 1.0
        return {"rise_linearity_correction": round(1.0 - f.get("rise_linearity", 1.0), 4),
                "fall_linearity_correction": round(1.0 - f.get("fall_linearity", 1.0), 4),
                "asymmetry_correction": round(-f.get("rise_fall_asym", 0.0), 4),
                "amplitude_scale": amp}
    if wtype == "pulse":
        amp = round(peak / rms, 4) if rms > 0 else 1.0
        return {"ringing_suppression_target": f.get("post_ringing", 0.0),
                "pulse_duty_cycle_measured": f.get("pulse_duty", 1.0),
                "amplitude_scale": amp}
    if wtype == "noise":
        return {"whitening_required": round(1.0 - f.get("spectral_flat", 1.0), 4),
                "rms_measured_nm": rms, "gaussianity_error": f.get("gaussianity_err", 0.0),
                "autocorr_lag1": f.get("autocorr", 0.0)}
    return {}

def format_cv(cv):
    lines = ["CORRECTION VECTOR:"]
    for k, v in cv.items():
        lines.append(f"  {k:<28} = {v:+.4f}" if isinstance(v, float) else f"  {k:<28} = {v}")
    return "\n".join(lines)


# ── metrics (identical to eval_zamba.py) ────────────────────────────────────

def simple_bleu1(hyp, ref):
    hyp_tokens = hyp.lower().split()
    ref_tokens = set(ref.lower().split())
    if not hyp_tokens:
        return 0.0
    return sum(1 for t in hyp_tokens if t in ref_tokens) / len(hyp_tokens)

def rouge_l(hyp, ref):
    hyp_tokens, ref_tokens = hyp.lower().split(), ref.lower().split()
    if not hyp_tokens or not ref_tokens:
        return 0.0
    m, n = len(ref_tokens), len(hyp_tokens)
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            dp[i][j] = dp[i-1][j-1] + 1 if ref_tokens[i-1] == hyp_tokens[j-1] \
                       else max(dp[i-1][j], dp[i][j-1])
    lcs = dp[m][n]
    prec, rec = lcs / n, lcs / m
    return 0.0 if prec + rec == 0 else 2 * prec * rec / (prec + rec)


# ── inference (zero-shot: this model is fine-tuned, no in-context example) ──

STOP_STRINGS = [tokenizer.eos_token] if tokenizer.eos_token else []

def run_inference(ex):
    prompt_text = f"{ex['system']}\n\n{ex['input']}\n\n"
    input_ids = tokenizer(prompt_text, return_tensors="pt",
                          add_special_tokens=False).input_ids.to(model.device)

    t0 = time.time()
    with torch.no_grad():
        output_ids = model.generate(
            input_ids,
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=False,  # greedy — fine-tuned model, deterministic eval
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=tokenizer.eos_token_id,
        )
    elapsed_s = time.time() - t0
    new_tokens = output_ids.shape[1] - input_ids.shape[1]

    gen_text = tokenizer.decode(output_ids[0][input_ids.shape[1]:], skip_special_tokens=True)
    for s in STOP_STRINGS:
        if s and s in gen_text:
            gen_text = gen_text[:gen_text.index(s)]

    # This model was never trained to emit a true stop token (see
    # finetune_mamba2.py's note on the abandoned EOS-training attempts), so
    # generation runs to MAX_NEW_TOKENS and sometimes continues past the
    # real answer into hallucinated echoes of the input's own section
    # headers (e.g. "\n\nMEASURED FEATURES..."). A real DIAGNOSIS/CORRECTION
    # answer is always exactly two lines with no blank line in it, so the
    # first blank line is a reliable cut point for anything after it.
    if "\n\n" in gen_text:
        gen_text = gen_text[:gen_text.index("\n\n")]
    gen_text = gen_text.strip()

    features = parse_features(ex["input"])
    cv = compute_cv(features)
    full_output = gen_text + "\n\n" + format_cv(cv)

    return gen_text, full_output, elapsed_s, new_tokens


# ── run ───────────────────────────────────────────────────────────────────────

results_path = RESULTS_DIR / "eval_results.jsonl"
metrics_path = RESULTS_DIR / "metrics_summary.txt"

per_type_bleu, per_type_rouge = defaultdict(list), defaultdict(list)
per_type_ms, per_type_toks = defaultdict(list), defaultdict(list)

total_start = time.time()
with open(results_path, "w") as fout:
    for idx, ex in enumerate(test_data):
        wtype = get_wtype(ex)
        try:
            gen_text, full_output, elapsed_s, new_tokens = run_inference(ex)
            ref_text = ex.get("output", "").strip()

            b1 = simple_bleu1(gen_text, ref_text)
            rl = rouge_l(gen_text, ref_text)
            elapsed_ms = elapsed_s * 1000

            per_type_bleu[wtype].append(b1)
            per_type_rouge[wtype].append(rl)
            per_type_ms[wtype].append(elapsed_ms)
            per_type_toks[wtype].append(new_tokens)

            fout.write(json.dumps({
                "idx": idx, "waveform": wtype, "generated": full_output,
                "reference": ref_text, "bleu1": round(b1, 4), "rouge_l": round(rl, 4),
                "tokens": new_tokens, "ms": round(elapsed_ms, 1),
            }) + "\n")
            fout.flush()

            ms_per_tok = elapsed_ms / new_tokens if new_tokens > 0 else 0
            print(f"[{idx+1:3d}/{len(test_data)}] {wtype:<7} | "
                  f"BLEU-1={b1:.3f} ROUGE-L={rl:.3f} | "
                  f"{new_tokens}tok {elapsed_ms:.0f}ms ({ms_per_tok:.1f}ms/tok)")
        except Exception as e:
            print(f"[{idx+1:3d}/{len(test_data)}] {wtype:<7} | ERROR: {e}")
            fout.write(json.dumps({"idx": idx, "waveform": wtype, "error": str(e)}) + "\n")
            fout.flush()

total_elapsed = time.time() - total_start

lines = ["=" * 60, "EVALUATION SUMMARY — mamba2-780m-hf (fine-tuned, zero-shot)",
          "=" * 60, f"Total samples: {len(test_data)}",
          f"Total time:    {total_elapsed/60:.1f} min\n"]

all_bleu, all_rouge, all_ms = [], [], []
for wtype in ["sine", "square", "ramp", "pulse", "noise"]:
    b, r, ms = per_type_bleu[wtype], per_type_rouge[wtype], per_type_ms[wtype]
    if not b:
        continue
    lines.append(f"{wtype:<8} n={len(b):3d} | BLEU-1={sum(b)/len(b):.3f}  "
                 f"ROUGE-L={sum(r)/len(r):.3f}  avg={sum(ms)/len(ms):.0f}ms  "
                 f"p50={sorted(ms)[len(ms)//2]:.0f}ms")
    all_bleu.extend(b); all_rouge.extend(r); all_ms.extend(ms)

lines.append("-" * 60)
lines.append(f"{'OVERALL':<8} n={len(all_bleu):3d} | BLEU-1={sum(all_bleu)/len(all_bleu):.3f}  "
             f"ROUGE-L={sum(all_rouge)/len(all_rouge):.3f}  "
             f"avg={sum(all_ms)/len(all_ms):.0f}ms  p50={sorted(all_ms)[len(all_ms)//2]:.0f}ms")
lines.append("=" * 60)
lines.append("\nFor comparison, the Zamba2-7B few-shot baseline was:")
lines.append("  BLEU-1=0.382  ROUGE-L=0.209  avg=~22000ms/sample")

summary = "\n".join(lines)
print("\n" + summary)
with open(metrics_path, "w") as f:
    f.write(summary + "\n")
print(f"\nResults: {results_path}\nMetrics: {metrics_path}")
